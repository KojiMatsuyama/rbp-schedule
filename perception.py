#!/usr/bin/env python3
"""認知モジュール（独立トランジション）— トークンチェック + 入力 → ベクトルトークン。

アーキテクチャ:
  プレース（状態: トークン1, トークン2…）
    → トランジション [認知─評価─決定─投射]
    → 作動（sos）

認知はトランジションの第一番目で、**まずトークンがそろっているかをチェック**する:
  - トークンの存在（そろっているか）
  - 行列: 何行何列か（次元チェック）
  - 変数: 型が正しいか
変数の型チェックと同様、存在・次元・型のみに限定し、中身の深いチェックはしない
（RBP行列の深い計算は評価/決定の役割）。認知は作動(sos)の一種ではなく、
ナビゲーター内 [認知─評価─決定─投射] のトランジションである。

本モジュールが集約する認知経路:
  check_vector()     — cron版: 事前生成ベクトルのトークンチェック（③認知）
  check_presence()   — 汎用: トークンのそろいチェック
  perceive()         — チャット版: メッセージ → 病害虫名 + ベクトルトークン

このファイルをトップレベルに置く理由（projection.py と同じ）:
  agentic_chat / scripts/rx_prescribe の両方から import するため。
  agentic_chat/ に置くと cron / server 側が agentic_chat/__init__.py
  (= LangGraph 全套) を巻き込む。
"""

