logger = logging.getLogger(__name__)

APP_ROOT = os.path.dirname(os.path.abspath(__file__))
DB_PATH = os.path.join(APP_ROOT, "data", "stb.db")

VECTOR_DIM = 10

# ================================================================
# 病害虫DB（唯一無二の正 — SQLite diseases テーブル）
# ================================================================
# RBP の10次元ベクトルの各軸 0〜9 は diseases.id 0〜9 に対応する。
# かつてのハードコード DISEASE_NAMES と手編集した複製（data/diseases.json 等）
# は廃止し、data/stb.db の diseases テーブルを唯一の正とした
# （bootstrap のシード元は db_setup.py の DISEASES_SEED）。
# data/diseases.js はその正から scripts/export_diseases.py が生成する静的スナップショット。
# DB 欠損・行数不一致は「次元↔名」対応を決められないため import 時に即失敗する。
def _load_disease_names() -> list[str]:
    try:
        conn = sqlite3.connect(DB_PATH)
        rows = conn.execute("SELECT name FROM diseases ORDER BY id").fetchall()
        conn.close()
    except sqlite3.Error as e:
        raise RuntimeError(
            f"病害虫DB を読めません（{DB_PATH}）。db_setup.py を実行してください。({e})"
        ) from e
    if len(rows) != VECTOR_DIM:
        raise RuntimeError(
            f"病害虫DB が {len(rows)} 行（本来 {VECTOR_DIM} 行）"
        )
    return [r[0] for r in rows]


