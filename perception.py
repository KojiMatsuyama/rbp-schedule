# =====================================================================
# トークンチェック（認知の核）— 発火の前提条件
# =====================================================================
# プレース（状態: トークン）→ トランジション[認知─評価─決定─投射] → 作動(sos)
# 認知は第一トランジションで、まずトークンがそろっているかをチェックする。
# 変数の型チェックと同様: 行列は「何行何列か」、変数は「型」。
# 存在・次元・型のみに限定し、中身の深いチェックはしない。


def check_vector(vector, dim: int = VECTOR_DIM) -> tuple[bool, str | None]:
    """
    ベクトルトークンチェック — list型 / dim次元 / 要素は2値 / トークン1個以上。

    Args:
        vector: チェック対象トークン（[0,1] * dim を想定）
        dim: 想定する次元（既定 VECTOR_DIM=10）

    Returns:
        OKなら (True, None)。NGなら (False, 理由)。
    """
    if not isinstance(vector, list):
        return False, f"トークンの型不一致: {type(vector).__name__}（listを想定）"
    if len(vector) != dim:
        return False, f"次元不一致: {len(vector)}次元（{dim}次元を想定）"
    if any(v not in (0, 1) for v in vector):
        return False, f"トークンの型不一致: 2値でない要素を含む {vector}"
    if not any(vector):
        return False, "トークンなし（全ゼロ）"
    return True, None


def check_presence(tokens: dict) -> tuple[bool, str | None]:
    """
    トークンのそろいチェック — 必須トークンが揃っているか（None・空文字でない）。

    Args:
        tokens: {"トークン名": 値, ...}

    Returns:
        全て揃っていれば (True, None)。不足なら (False, 不足トークン名)。
    """
    missing = [name for name, value in tokens.items() if value is None or value == ""]
    if missing:
        return False, f"トークン不足: {'、'.join(missing)}"
    return True, None

