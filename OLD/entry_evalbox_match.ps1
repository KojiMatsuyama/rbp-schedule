# 各EVごとに全22EBスコアを計算・出力
$allResults = @()
$evNum = 0
foreach ($line in $raw) {
    $evNum++
    $parts = $line -split ','
    $date = $parts[0]
    $entry = @()
    for ($k = 1; $k -lt 11; $k++) { $entry += [double]$parts[$k] }

    # 全22EBとの内積を計算
    $allScores = @()
    foreach ($kv in $EVAL_BOXES.GetEnumerator()) {
        $sid = [int]$kv.Key
        $score = Dot $entry $kv.Value.vec
        $allScores += [PSCustomObject]@{
            EBNum = $sid
            Name  = $kv.Value.name
            Score = $score
        }
    }
    # スコア降順でソート
    $sorted = $allScores | Sort-Object Score -Descending

    # ENTRY_VECTORの非ゼロ成分
    $nonzero = @()
    for ($j = 0; $j -lt 10; $j++) {
        if ($entry[$j] -gt 0) { $nonzero += "$($PESTS[$j]):$($entry[$j].ToString('F3'))" }
    }
    $entryStr = if ($nonzero.Count -gt 0) { $nonzero -join ", " } else { "(all 0)" }

    # 結果を保存
    $allResults += [PSCustomObject]@{
        EVNum = $evNum
        Date  = $date
        Entry = $entry
        Scores = $sorted
    }

    # 出力（各行: EV番号, 日付, ENTRY_VECTOR, 上位5EB）
    $top5 = $sorted | Select-Object -First 5
    $top5Str = ($top5 | ForEach-Object {
        "EB-$($_.EBNum.ToString('D2'))=$($_.Score.ToString('F3'))"
    }) -join ", "

    Write-Host "EV-$($evNum.ToString('D3')) ($date) | $entryStr" -ForegroundColor Yellow
    Write-Host "  Top5: $top5Str" -ForegroundColor White

    # スコア>0 のEBをすべて表示
    $nonzeroScores = $sorted | Where-Object { $_.Score -gt 0 }
    $nzStr = ($nonzeroScores | ForEach-Object {
        "  EB-$($_.EBNum.ToString('D2')) ($($_.Name)): $($_.Score.ToString('F3'))"
    }) -join "`n"
    if ($nzStr) { Write-Host $nzStr -ForegroundColor Gray }

    Write-Host ""
}

# ===== 集計 =====
Write-Host "==============================================================" -ForegroundColor Cyan
Write-Host "  集計: EB番号別（スコア>0の出現回数）" -ForegroundColor Cyan
Write-Host "==============================================================" -ForegroundColor Cyan
Write-Host ""

$ebCount = @{}
$ebTotalScore = @{}
foreach ($kv in $EVAL_BOXES.GetEnumerator()) {
    $sid = [int]$kv.Key
    $ebCount[$sid] = 0
    $ebTotalScore[$sid] = 0.0
}

foreach ($r in $allResults) {
    foreach ($s in $r.Scores) {
        if ($s.Score -gt 0) {
            $ebCount[$s.EBNum]++
            $ebTotalScore[$s.EBNum] += $s.Score
        }
    }
}

Write-Host "  $($('EB番号').PadRight(8)) $($('名称').PadRight(45)) $($('スコア>0回数').PadRight(12)) $($('平均スコア').PadRight(12)) $($('合計スコア').PadRight(12))" -ForegroundColor Cyan
Write-Host "  $($('-' * 92))" -ForegroundColor Gray

foreach ($sid in ($ebCount.Keys | Sort-Object)) {
    $name = $EVAL_BOXES[$sid].name
    $count = $ebCount[$sid]
    $avg = if ($count -gt 0) { $ebTotalScore[$sid] / $count } else { 0.0 }
    $total = $ebTotalScore[$sid]
    Write-Host "  EB-$($sid.ToString('D2')) ($($name.PadRight(43))) $($count.ToString().PadRight(12)) $($avg.ToString('F3').PadRight(12)) $($total.ToString('F3').PadRight(12))"
}

Write-Host ""
Write-Host "  合計: $($allResults.Count)日" -ForegroundColor Cyan
